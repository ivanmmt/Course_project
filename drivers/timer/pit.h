/* =============================================================================
 * drivers/timer/pit.h
 * PIT — Programmable Interval Timer (Intel 8253/8254)
 *
 * PIT генерирует прерывания IRQ0 с заданной частотой.
 * Базовая частота = 1193182 Гц. Делитель задаётся программно.
 * Используется для системного таймера (тики, sleep, планировщик).
 * ============================================================================= */

#ifndef PIT_H
#define PIT_H

#include <stdint.h>

/* Порты PIT */
#define PIT_CHANNEL0  0x40   /* канал 0 (связан с IRQ0) */
#define PIT_CMD       0x43   /* командный регистр */

/* Базовая частота PIT в Гц */
#define PIT_BASE_FREQ 1193182

/* --- API --- */
void     pit_init(uint32_t frequency_hz);   /* инициализировать с заданной частотой */
uint32_t pit_get_ticks(void);               /* сколько тиков прошло с загрузки */
void     pit_sleep(uint32_t ms);            /* задержка в миллисекундах */

#endif /* PIT_H */
