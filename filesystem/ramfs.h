/* =============================================================================
 * filesystem/ramfs.h
 * RAM Filesystem — файловая система целиком в памяти
 *
 * ЗАЧЕМ:
 * На начальном этапе у нас нет драйвера диска. RamFS позволяет
 * иметь полноценное дерево файлов прямо в RAM — идеально для:
 *   - initrd (начальный RAM-диск, как в Linux)
 *   - хранения встроенных программ ядра
 *   - тестирования VFS без железа
 *
 * СТРУКТУРА:
 * Каждый файл — это ramfs_node_t с динамическим буфером данных (kmalloc).
 * При записи буфер растёт автоматически через krealloc.
 * Директории хранят массив указателей на дочерние ноды.
 * ============================================================================= */

#ifndef RAMFS_H
#define RAMFS_H

#include "vfs.h"

/* Инициализировать ramfs и вернуть корневую ноду */
vfs_node_t* ramfs_init(void);

/* Создать файл с предзаполненным содержимым */
vfs_node_t* ramfs_create_file(vfs_node_t* parent,
                               const char* name,
                               const uint8_t* data,
                               uint32_t size);

/* Создать директорию */
vfs_node_t* ramfs_create_dir(vfs_node_t* parent, const char* name);

/* Получить статистику (для отладки) */
void ramfs_dump(vfs_node_t* node, int depth);

#endif /* RAMFS_H */
