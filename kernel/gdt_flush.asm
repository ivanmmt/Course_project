; =============================================================================
; kernel/gdt_flush.asm
; Загрузка GDT и обновление сегментных регистров
;
; ЗАЧЕМ ЭТО В ASM:
; После LGDT нужно выполнить "дальний прыжок" (far jump) чтобы обновить
; регистр CS (code segment). Far jump нельзя сделать из C — нужен ASM.
; Остальные сегментные регистры (DS, ES, FS, GS, SS) обновляются через mov.
; =============================================================================

bits 32
global gdt_flush

gdt_flush:
    ; Аргумент — указатель на gdt_ptr_t, лежит на стеке
    mov eax, [esp+4]

    ; Загружаем GDT: указываем процессору где искать дескрипторы
    lgdt [eax]

    ; Far jump: меняем CS на наш селектор кода ядра (0x08 = дескриптор 1)
    ; Синтаксис: jmp selector:offset
    ; Это автоматически сбросит pipeline процессора и применит новый CS
    jmp 0x08:.flush

.flush:
    ; Обновляем все остальные сегментные регистры на сегмент данных ядра
    ; 0x10 = дескриптор 2 (данные ядра, ring 0)
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax

    ret

section .note.GNU-stack noalloc noexec nowrite progbits
