/* =============================================================================
 * kernel/gdt.c
 * Реализация Global Descriptor Table
 *
 * ЗАЧЕМ НУЖНА GDT:
 * В x86 защищённом режиме каждый доступ к памяти проходит через сегментную
 * систему. Процессор проверяет: есть ли у кода нужный уровень привилегий
 * для работы с этим сегментом? GDT — это таблица, описывающая все сегменты.
 *
 * GRUB уже настроил временную GDT, но нам нужна своя — правильная,
 * с нашими уровнями привилегий для будущих задач пользователя (ring 3).
 * ============================================================================= */

#include "gdt.h"

/* Сама таблица дескрипторов — глобальный массив */
static gdt_entry_t gdt_table[GDT_ENTRIES];

/* Указатель который загрузим через LGDT */
static gdt_ptr_t   gdt_pointer;

/* =============================================================================
 * gdt_set_entry — заполнить один дескриптор GDT
 *
 * base:        32-битный базовый адрес сегмента
 * limit:       20-битный лимит (в байтах или страницах, зависит от гранулярности)
 * access:      байт доступа (тип, привилегии)
 * granularity: байт флагов (гранулярность, 32/64-бит)
 * ============================================================================= */
static void gdt_set_entry(int idx, uint32_t base, uint32_t limit,
                           uint8_t access, uint8_t granularity)
{
    gdt_entry_t* e = &gdt_table[idx];

    /* Разбиваем базу на три части (x86 legacy формат) */
    e->base_low  = (base & 0x0000FFFF);
    e->base_mid  = (base & 0x00FF0000) >> 16;
    e->base_high = (base & 0xFF000000) >> 24;

    /* Разбиваем лимит: 16 бит в limit_low, 4 бита в granularity */
    e->limit_low   = (limit & 0x0000FFFF);
    /* Верхние 4 бита лимита идут в старший ниббл granularity */
    e->granularity = (granularity & 0xF0) | ((limit >> 16) & 0x0F);

    e->access = access;
}

/* =============================================================================
 * gdt_init — настроить и загрузить GDT
 * ============================================================================= */
void gdt_init(void)
{
    /* --- Дескриптор 0: Нулевой (обязателен по стандарту x86) ---
     * Любое обращение через нулевой дескриптор вызовет исключение.
     * Это защита от случайного использования незаинициализированных регистров. */
    gdt_set_entry(0, 0, 0, 0, 0);

    /* --- Дескриптор 1: Сегмент кода ядра (ring 0) ---
     * base=0, limit=0xFFFFF (с гранулярностью 4KB → покрывает 4GB)
     * Flat memory model: вся память — один сегмент */
    gdt_set_entry(1,
        0,           /* base: начало с 0 */
        0xFFFFF,     /* limit: 1 048 575 страниц × 4KB = 4GB */
        GDT_CODE_KERNEL,
        GDT_GRAN_4K | GDT_GRAN_32
    );

    /* --- Дескриптор 2: Сегмент данных ядра (ring 0) --- */
    gdt_set_entry(2,
        0,
        0xFFFFF,
        GDT_DATA_KERNEL,
        GDT_GRAN_4K | GDT_GRAN_32
    );

    /* --- Дескриптор 3: Сегмент кода пользователя (ring 3) ---
     * Понадобится когда добавим пользовательские процессы */
    gdt_set_entry(3,
        0,
        0xFFFFF,
        GDT_CODE_USER,
        GDT_GRAN_4K | GDT_GRAN_32
    );

    /* --- Дескриптор 4: Сегмент данных пользователя (ring 3) --- */
    gdt_set_entry(4,
        0,
        0xFFFFF,
        GDT_DATA_USER,
        GDT_GRAN_4K | GDT_GRAN_32
    );

    /* Заполняем указатель на GDT */
    gdt_pointer.limit = (sizeof(gdt_entry_t) * GDT_ENTRIES) - 1;
    gdt_pointer.base  = (uint32_t)&gdt_table;

    /* Загружаем GDT и сбрасываем сегментные регистры (реализовано в ASM) */
    gdt_flush((uint32_t)&gdt_pointer);
}
